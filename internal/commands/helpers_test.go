// baseConfig is the goro.yaml most tests start from. UserRepo uses mysql, so it is
// transactional and the Users service embeds service.Transactor in its interface.
const baseConfig = `
app:
  name: demo
  module: demo

storages:
  - mysql

use_case:
  deps:
    - Users
    - Billing
  methods:
    - SignIn
    - SignUp

services:
  - name: Users
    methods:
      - Create
    deps:
      - UserRepo

  - name: Billing
    methods:
      - Charge

adapters:
  - name: UserRepo
    storage: mysql
    methods:
      - GetByID
`

// markerLine is the generated marker from ADR 0001.
var markerLine = regexp.MustCompile(`^// Code generated by goro\b.*DO NOT EDIT\.$`)

// newConfig loads baseConfig through the real config loader and points it at workDir. Each
// call returns a fresh value, so tests can change it to stand for an edited goro.yaml.
// The file lives outside workDir so it doesn't count as part of the project.
func newConfig(t *testing.T, workDir string) config.Config {
	t.Helper()

	path := filepath.Join(t.TempDir(), "goro.yaml")
	if err := os.WriteFile(path, []byte(baseConfig), 0o644); err != nil {
		t.Fatal(err)
	}

	cfg, err := config.NewConfig(path)
	if err != nil {
		t.Fatalf("load config: %v", err)
	}
	cfg.App.WorkDir = workDir

	return cfg
}

// addAuditRepo stands for a goro.yaml edit: a new mysql adapter AuditRepo that the Users service
// depends on.
func addAuditRepo(cfg *config.Config) {
	cfg.Adapters = append(cfg.Adapters, config.Adapter{Name: "AuditRepo", Storage: "mysql", Methods: []string{"Write"}})
	for i := range cfg.Services {
		if cfg.Services[i].Name == "Users" {
			cfg.Services[i].Deps = append(cfg.Services[i].Deps, "AuditRepo")
		}
	}
}

func initProject(t *testing.T, cfg config.Config) {
	t.Helper()

	if err := commands.Init(cfg, commands.Options{SkipGoMod: true}); err != nil {
		t.Fatalf("init: %v", err)
	}
}

func update(t *testing.T, cfg config.Config) commands.Report {
	t.Helper()

	report, err := commands.Update(cfg, commands.Options{SkipGoMod: true, Out: io.Discard})
	if err != nil {
		t.Fatalf("update: %v", err)
	}

	return report
}

func readFile(t *testing.T, dir, rel string) string {
	t.Helper()

	b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatalf("read %s: %v", rel, err)
	}

	return string(b)
}

func writeFile(t *testing.T, dir, rel, content string) {
	t.Helper()

	path := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o775); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func exists(dir, rel string) bool {
	_, err := os.Stat(filepath.Join(dir, filepath.FromSlash(rel)))
	return err == nil
}

// handEdit appends user code to a Go file's content.
func handEdit(content string) string {
	return content + "\n// handWritten is user code that goro update must keep.\nfunc handWritten() string { return \"kept\" }\n"
}

// hasMarker reports whether a marker line comes before the package clause.
func hasMarker(content string) bool {
	for _, line := range strings.Split(content, "\n") {
		if strings.HasPrefix(line, "package ") {
			return false
		}
		if markerLine.MatchString(line) {
			return true
		}
	}

	return false
}

// removeMarker drops the marker line, which is how a user takes ownership of a generated file.
func removeMarker(content string) string {
	lines := strings.Split(content, "\n")
	kept := make([]string, 0, len(lines))
	for _, line := range lines {
		if !markerLine.MatchString(line) {
			kept = append(kept, line)
		}
	}

	return strings.Join(kept, "\n")
}

// actionOf returns the action the report gives for path, or "" when the report doesn't list it.
func actionOf(r commands.Report, path string) commands.Action {
	for _, f := range r.Files {
		if f.Path == path {
			return f.Action
		}
	}

	return ""
}

func assertAction(t *testing.T, r commands.Report, path string, want commands.Action) {
	t.Helper()

	got := actionOf(r, path)
	if got == "" {
		t.Errorf("report doesn't list %s, want action %q", path, want)
		return
	}
	if got != want {
		t.Errorf("report gives %s action %q, want %q", path, got, want)
	}
}

func orphans(r commands.Report) []string {
	res := make([]string, 0)
	for _, f := range r.Files {
		if f.Action == commands.ActionOrphan {
			res = append(res, f.Path)
		}
	}
	sort.Strings(res)

	return res
}

type entry struct {
	isDir   bool
	content string
	modTime time.Time
}

// snapshot records every file and directory under dir by its slash-separated relative path.
func snapshot(t *testing.T, dir string) map[string]entry {
	t.Helper()

	res := make(map[string]entry)
	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		rel = filepath.ToSlash(rel)

		if info.IsDir() {
			res[rel] = entry{isDir: true}
			return nil
		}

		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		res[rel] = entry{content: string(b), modTime: info.ModTime()}

		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	return res
}

// ageFiles sets every file's modification time to a fixed past time, so a later snapshot shows
// any file that was written again, even with the same content.
func ageFiles(t *testing.T, dir string) {
	t.Helper()

	old := time.Date(2001, 1, 1, 0, 0, 0, 0, time.UTC)
	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		return os.Chtimes(path, old, old)
	})
	if err != nil {
		t.Fatal(err)
	}
}

// assertNoChanges fails for every path that was added, removed or written between two snapshots.
func assertNoChanges(t *testing.T, before, after map[string]entry) {
	t.Helper()

	paths := make([]string, 0, len(before)+len(after))
	for p := range before {
		paths = append(paths, p)
	}
	for p := range after {
		if _, ok := before[p]; !ok {
			paths = append(paths, p)
		}
	}
	sort.Strings(paths)

	for _, p := range paths {
		b, inBefore := before[p]
		a, inAfter := after[p]
		switch {
		case !inAfter:
			t.Errorf("%s was deleted", p)
		case !inBefore:
			t.Errorf("%s was created", p)
		case b.isDir || a.isDir:
			if b.isDir != a.isDir {
				t.Errorf("%s changed between file and directory", p)
			}
		case b.content != a.content:
			t.Errorf("%s was changed", p)
		case !b.modTime.Equal(a.modTime):
			t.Errorf("%s was written again with the same content", p)
		}
	}
}

// assertMarkedFilesMatchFreshInit checks that every marked file a fresh init with cfg writes is
// the same in dir, which is what regenerating every marked file means.
func assertMarkedFilesMatchFreshInit(t *testing.T, dir string, cfg config.Config) {
	t.Helper()

	fresh := cfg
	fresh.App.WorkDir = t.TempDir()
	initProject(t, fresh)

	for path, e := range snapshot(t, fresh.App.WorkDir) {
		if e.isDir || !hasMarker(e.content) {
			continue
		}

		got, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(path)))
		if err != nil {
			t.Errorf("marked file %s: %v", path, err)
			continue
		}
		if string(got) != e.content {
			t.Errorf("marked file %s differs from a fresh init with the same goro.yaml", path)
		}
	}
}

func parseGo(t *testing.T, dir, rel string) *ast.File {
	t.Helper()

	f, err := parser.ParseFile(token.NewFileSet(), rel, readFile(t, dir, rel), 0)
	if err != nil {
		t.Fatalf("parse %s: %v", rel, err)
	}

	return f
}

// interfaces returns the interface types a Go file declares, by name.
func interfaces(f *ast.File) map[string]*ast.InterfaceType {
	res := make(map[string]*ast.InterfaceType)
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			ts := spec.(*ast.TypeSpec)
			if it, ok := ts.Type.(*ast.InterfaceType); ok {
				res[ts.Name.Name] = it
			}
		}
	}

	return res
}

// embeds reports whether an interface embeds pkg.name, such as service.Transactor.
func embeds(it *ast.InterfaceType, pkg, name string) bool {
	for _, m := range it.Methods.List {
		if len(m.Names) != 0 {
			continue
		}
		sel, ok := m.Type.(*ast.SelectorExpr)
		if !ok {
			continue
		}
		if x, ok := sel.X.(*ast.Ident); ok && x.Name == pkg && sel.Sel.Name == name {
			return true
		}
	}

	return false
}

// funcParams returns the number of parameters of the top-level function name, or -1.
func funcParams(f *ast.File, name string) int {
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != name {
			continue
		}
		n := 0
		for _, field := range fn.Type.Params.List {
			if len(field.Names) == 0 {
				n++
			}
			n += len(field.Names)
		}
		return n
	}

	return -1
}

// callArgs returns the number of arguments of the first call to pkg.name in f, or -1.
func callArgs(f *ast.File, pkg, name string) int {
	res := -1
	ast.Inspect(f, func(n ast.Node) bool {
		if res >= 0 {
			return false
		}
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if x, ok := sel.X.(*ast.Ident); ok && x.Name == pkg && sel.Sel.Name == name {
			res = len(call.Args)
			return false
		}
		return true
	})

	return res
}
