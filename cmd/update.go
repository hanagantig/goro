package cmd

import (
	"github.com/hanagantig/goro/internal/commands"
	"github.com/hanagantig/goro/internal/pkg/log"
	"github.com/spf13/cobra"
)

var updateDryRun bool

// updateCmd represents the update command
var updateCmd = &cobra.Command{
	Use:   "update",
	Short: "Updates your code after goro.yaml changes",
	Long: `Update brings the service in line with goro.yaml: the one in the current directory, or the
file --config names.

It regenerates the files that start with "// Code generated by goro. DO NOT EDIT.",
creates the files that are missing, and leaves every other file as it is. It deletes
nothing: code that goro.yaml no longer lists is reported as orphaned.

Use --dry-run to see what update would do, with a diff for every regenerated file.`,
	Run: func(cmd *cobra.Command, args []string) {
		cfg, err := commands.LoadConfig(goroCnf)
		if err != nil {
			log.Fatal(err)
		}

		_, err = commands.Update(cfg, commands.Options{DryRun: updateDryRun})
		if err != nil {
			log.Fatal(err)
		}
	},
}

func init() {
	updateCmd.Flags().BoolVar(&updateDryRun, "dry-run", false, "print what update would do, with a diff for each regenerated file, and write nothing")
}
